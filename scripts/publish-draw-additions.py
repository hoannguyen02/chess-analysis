"""Build practice/PDF additions from explicit selections and verification evidence."""
import json,pathlib,collections,chess
ROOT=pathlib.Path(__file__).resolve().parent.parent;P=ROOT/'scripts/fixtures/draw-practice'
def main():
 rows=json.load(open(P/'selected-additions.json'))['records']+json.load(open(P/'intro-additions.json'))['records']
 final={r['id']:r for r in json.load(open(P/'addition-final-review.json'))['records']}
 baseline=json.load(open(P/'curated-selection.json'))['selected'];counts=collections.Counter(r['level'] for r in baseline+rows)
 expected={'Beginner':24,'A':24,'B':28,'C':29,'C*':25,'D':27}
 assert counts==expected,counts
 assert len({r['fen'].split(' ')[0]+' '+r['fen'].split(' ')[1] for r in baseline+rows})==157
 groups=collections.defaultdict(list);manifest=[]
 for ordinal,r in enumerate(rows,1):
  composed=r.get('sourceKind')=='composed';study=r.get('sourceKind')=='study'
  if not composed:assert final[r['id']]['status']=='reviewed',r['id']
  b=chess.Board(r['fen']);assert b.is_valid()
  for s in r['moves']:b.push_san(s)
  outcome=r.get('outcome','stalemate' if r['category']=='stalemate' else 'repetition')
  if outcome=='repetition':assert b.is_repetition(3),r['id']
  if outcome=='stalemate':assert b.is_stalemate(),r['id']
  if outcome=='material':assert b.is_insufficient_material(),r['id']
  if composed:title=f'Thế cờ biên soạn · {ordinal-97:02d}';source='original-composition'
  elif study:title='Thế cờ nghiên cứu · '+r['studyCredit'];source=r['sourceUrl']
  else:
   h=r['headers'];title=f"{h['White']} – {h['Black']} · {h.get('Date','')}";source=r['sourceUrl']
  explanation=r['solution']
  if outcome=='repetition':
   explanation+=' Phương án mẫu đưa thế cờ lặp lại ba lần, cho phép yêu cầu hòa hợp lệ; ván chưa tự động kết thúc.'
   if len(r['moves'])>r.get('actualGamePlies',0):explanation+=' Phần sau khi ván gốc kết thúc là phương án minh họa tiếp tục chu kỳ chiếu.'
  if not composed:explanation+=' Các nước đáp trong phương án không nhất thiết là duy nhất.'
  exercise=dict(title=title,prompt='Tìm cách giữ hòa. Kiểm tra nước đáp của đối phương trước khi chọn nước đi.',fen=r['fen'],moves=r['moves'],goal='draw',outcome=outcome,mode='interactive',beginner=r['level']=='Beginner',solution=explanation,source=source)
  if not composed and study:exercise['url']=source
  if r.get('previousMove'):exercise['previousMove']=r['previousMove']
  if r['level']!='Beginner':exercise['difficulty']=dict(level=r['level'],reason=r['solution'],status='suggested',solverMoves=r['solverDecisions'],sacrificeCount=len(r.get('sacrifices',[])))
  if r['level'] in ['C','D']:assert exercise['difficulty']['sacrificeCount']>0
  groups[r['category']].append(exercise)
  manifest.append({k:r[k] for k in ['id','level','fen','moves','category','aspect','solution','gameId']})
 (ROOT/'src/lib/chess/draw-additions.ts').write_text('// Generated by scripts/publish-draw-additions.py; explicit selections only.\nimport type { DrawExercise } from "./draw-practice";\nexport const drawAdditions: Record<string, DrawExercise[]> = '+json.dumps(groups,ensure_ascii=False,indent=2)+';\n')
 (P/'published-additions.json').write_text(json.dumps(dict(counts=counts,records=manifest),ensure_ascii=False,indent=2)+'\n')
 print('Published',len(rows),'additions;',dict(counts))
if __name__=='__main__':main()
