const fs = require('fs');
(async () => {
  const { Chess } = await import(
    process.cwd() + '/node_modules/chess.js/chess.js'
  );
  const games = fs
    .readFileSync(process.argv[2], 'utf8')
    .split(/(?=\[Event ")/)
    .filter(Boolean);
  const found = [];
  let invalid = 0;
  for (const pgn of games) {
    if (!pgn.includes('[Result "1/2-1/2"]')) continue;
    const g = new Chess();
    if (!g.load_pgn(pgn)) {
      invalid++;
      continue;
    }
    const h = g.header(),
      moves = g.history();
    const board = new Chess();
    const fens = [board.fen()];
    for (const m of moves) {
      board.move(m);
      fens.push(board.fen());
    }
    const key = (f) => f.split(' ').slice(0, 4).join(' ');
    const hits = fens
      .map((f, i) => (key(f) === key(fens.at(-1)) ? i : -1))
      .filter((i) => i >= 0);
    if (hits.length !== 3) continue;
    const start = hits[0],
      line = moves.slice(start);
    if (
      // Exclude repetitions beginning during moves 1–5 (either side).
      start < 10 ||
      line.length < 8 ||
      line.length > 16 ||
      line.some((m) => /[+#]/.test(m))
    )
      continue;
    const check = new Chess(fens[start]);
    let early = check.game_over();
    for (let i = 0; i < line.length; i++) {
      check.move(line[i]);
      if (check.game_over() && i < line.length - 1) early = true;
    }
    if (early || !check.in_threefold_repetition()) continue;
    found.push({
      headers: h,
      fen: fens[start],
      moves: line,
      previousMove: { fen: fens[start - 1], move: moves[start - 1] },
      startPly: start,
      pgn,
      pieces: fens[start].split(' ')[0].replace(/[^a-z]/gi, '').length,
    });
  }
  found.sort(
    (a, b) =>
      a.pieces - b.pieces || b.headers.Date.localeCompare(a.headers.Date)
  );
  const seen = new Set();
  const unique = found.filter((x) => {
    let k = x.fen.split(' ').slice(0, 4).join(' ');
    if (seen.has(k)) return false;
    seen.add(k);
    return true;
  });
  // Order by the whole recorded game's length, not just the exercise tail.
  // Sort after deduplication so changing presentation does not change selection.
  unique.sort(
    (a, b) => a.startPly + a.moves.length - (b.startPly + b.moves.length)
  );

  const sourceUrl = 'https://www.pgnmentor.com/players/Carlsen.zip';
  const fixture = unique.map(({ pgn, startPly, headers }) => ({
    pgn,
    startPly,
    headers,
    sourceUrl,
  }));
  const exercises = unique.map((item) => {
    const { headers: h, fen, moves, previousMove, startPly } = item;
    const player = (name) => name.replace(/,/g, ', ');
    const start = Math.floor(startPly / 2) + 1;
    const numbered = moves
      .map((move, i) => {
        const ply = startPly + i;
        return `${Math.floor(ply / 2) + 1}${ply % 2 ? '...' : '.'} ${move}`;
      })
      .join(' ');
    return {
      title: `${player(h.White)} – ${player(h.Black)} · ${h.Date}`,
      prompt: `${h.Event}, vòng ${h.Round}. ${fen.split(' ')[1] === 'w' ? 'Trắng' : 'Đen'} đi, từ nước ${start}. Tìm chuỗi lặp lại không chiếu đã xuất hiện trong ván hòa này.`,
      fen,
      moves,
      previousMove,
      outcome: 'repetition',
      mode: 'interactive',
      source: `PGN Mentor · ${h.Event} · ${h.Date}`,
      solution: `${numbered}. Kết quả ván đấu: ½–½. Thế ở đầu bài xuất hiện thêm hai lần trong chuỗi này, với cùng bên đến lượt và cùng quyền đi quân. Đây là diễn biến thực tế; không khẳng định mọi nước đáp của đối thủ đều bị bắt buộc.`,
    };
  });
  fs.writeFileSync(
    'scripts/fixtures/draw-practice/real-repetition-games.json',
    JSON.stringify(fixture, null, 2) + '\n'
  );
  fs.writeFileSync(
    'src/lib/chess/real-repetition.ts',
    "// Generated by scripts/import-real-repetition.cjs from recorded drawn games.\nimport type { DrawExercise } from './draw-practice';\n\nexport const realRepetitionExercises: DrawExercise[] = " +
      JSON.stringify(exercises, null, 2) +
      ';\n'
  );
  console.log({ scanned: games.length, invalid, selected: unique.length });
})();
