// Rebuild local exercises from audited source records; no network access.
const fs = require('node:fs');
const input = JSON.parse(
  fs.readFileSync(
    'scripts/fixtures/draw-practice/expanded-draw-sources.json',
    'utf8'
  )
);
const categories = {};
const fortressMotifs = {
  'rook-pawn-corner': [
    'Vua giữ góc trước Tốt biên',
    'Vua bên phòng thủ giữ góc phong cấp của Tốt biên. Bên hơn Tốt không thể đuổi Vua khỏi góc nếu phòng thủ đúng.',
  ],
  'wrong-bishop-rook-pawn': [
    'Tượng sai màu và Tốt biên',
    'Tượng không kiểm soát ô phong cấp của Tốt biên. Vua phòng thủ trú ở góc đó và tránh tự rời vùng an toàn.',
  ],
  'bishop-safe-corner': [
    'Tượng giữ góc trước Xe',
    'Vua phòng thủ chọn góc khác màu ô của Tượng. Giữ Tượng an toàn và phối hợp với Vua để chống các nước chiếu của Xe.',
  ],
  'queen-vs-seventh-rank-pawn': [
    'Tốt hàng 7 giữ hòa trước Hậu',
    'Vua ở gần Tốt biên hoặc Tốt Tượng trên hàng 7. Nguy cơ hết nước đi giúp cản Hậu; Vua bên có Hậu còn quá xa để hỗ trợ.',
  ],
};
for (const [category, records] of Object.entries(input.games)) {
  categories[category] = records.map((r) => {
    const date =
      r.headers.Date && !r.headers.Date.includes('?')
        ? r.headers.Date
        : r.headers.UTCDate || 'Ván đấu trực tuyến';
    const side = r.fen.split(' ')[1] === 'w' ? 'Trắng' : 'Đen';
    const names = `${r.headers.White.replace(/,/g, ', ')} – ${r.headers.Black.replace(/,/g, ', ')}`;
    const label =
      category === 'fortress'
        ? fortressMotifs[r.motif][0]
        : {
            'perpetual-check': 'Chiếu giữ hòa',
            stalemate: 'Bẫy hết nước đi',
            'insufficient-material': 'Đổi quân giữ hòa',
          }[category];
    const start = Number(r.fen.split(' ')[5]);
    const context = `${r.headers.Event} · ${date}. ${side} đi từ nước ${start}.`;
    let prompt, solution;
    if (category === 'fortress') {
      prompt = `${context} Theo dõi cách bên phòng thủ giữ vùng an toàn trong ván hòa này.`;
      solution = `${fortressMotifs[r.motif][1]} Tất cả thế trong đoạn đã chọn được bảng tàn cuộc xác nhận là hòa nếu đi đúng. Đây là các nước đã chơi; hết đoạn không có nghĩa ván cờ tự động hòa. Mở ván gốc để xem toàn bộ diễn biến.`;
    } else if (category === 'perpetual-check') {
      prompt = `${context} Tìm chuỗi chiếu để lặp lại thế cờ và hòa.`;
      solution =
        'Chuỗi chiếu trong ván thật đưa đến thế lặp lại ba lần. Giữ nhịp chiếu và theo dõi ô thoát của Vua. Các nước đáp ở đây là diễn biến đã được chơi, không khẳng định tất cả đều bắt buộc.';
    } else if (category === 'stalemate') {
      prompt = `${context} Tìm nước tạo cơ hội hết nước đi như trong ván đấu.`;
      solution =
        'Sau nước đáp đã được chơi, bên đến lượt không bị chiếu nhưng không còn nước hợp lệ: hòa do hết nước đi. Đây là một bẫy trong ván thật; không khẳng định đối thủ bắt buộc phải mắc bẫy.';
    } else {
      prompt = `${context} Tìm nước đưa thế cờ về hòa do không đủ lực chiếu hết.`;
      solution =
        'Sau nước này, các quân còn lại không thể tạo chiếu hết bằng bất kỳ chuỗi nước hợp lệ nào. Vì vậy ván cờ hòa ngay. Kết quả này được xác nhận từ vị trí cuối của ván đấu.';
    }
    return {
      title: `${label} · ${names} · ${date}`,
      prompt,
      fen: r.fen,
      moves: r.moves,
      previousMove: r.previousMove,
      outcome: {
        'perpetual-check': 'repetition',
        stalemate: 'stalemate',
        'insufficient-material': 'material',
        fortress: 'fortress',
      }[category],
      mode: category === 'fortress' ? 'study' : 'interactive',
      solution,
      source: r.sourceUrl,
    };
  });
}
fs.writeFileSync(
  'src/lib/chess/draw-expansion.ts',
  `// Generated by scripts/build-draw-expansion.cjs. Provenance and audits live in scripts/fixtures/draw-practice/.\nimport type { DrawExercise } from './draw-practice';\n\nexport const expandedDrawExercises: Record<string, DrawExercise[]> = ${JSON.stringify(categories, null, 2)};\n`
);
console.log(
  Object.fromEntries(Object.entries(categories).map(([k, v]) => [k, v.length]))
);
